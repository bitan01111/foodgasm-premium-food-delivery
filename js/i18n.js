let currentLang = localStorage.getItem('fg_lang') || 'en';

function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) langCode = 'en';
  currentLang = langCode;
  localStorage.setItem('fg_lang', langCode);

  const langObj = I18N_LANGUAGES.find(l => l.code === langCode) || I18N_LANGUAGES[0];
  const langCodeEl = document.getElementById('current-lang-code');
  const langFlagEl = document.getElementById('current-flag');
  if (langCodeEl) langCodeEl.textContent = langCode.toUpperCase();
  if (langFlagEl) langFlagEl.textContent = langObj.flag;

  // Translate all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[langCode][key]) {
      el.textContent = TRANSLATIONS[langCode][key];
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (TRANSLATIONS[langCode][key]) {
      el.setAttribute('placeholder', TRANSLATIONS[langCode][key]);
    }
  });

  // Trigger app rerender if active
  if (typeof window.onLanguageChange === 'function') {
    window.onLanguageChange(langCode);
  }
}

function t(key, fallback = '') {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) ||
         (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) ||
         fallback ||
         key;
}

window.I18N = {
  languages: I18N_LANGUAGES,
  get current() { return currentLang; },
  setLanguage,
  t
};
